import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const lock=JSON.parse(fs.readFileSync(path.join(root,'validation/contract-lock.json'),'utf8'));
if(lock.schema_version!==1||lock.kind!=='catalogs'||lock.contract_version!==2||!/^[a-f0-9]{40}$/.test(lock.commit)||Object.keys(lock.files).join()!=='catalogs.mjs')throw Error('Invalid pinned catalog contract');
const actual=createHash('sha256').update(fs.readFileSync(path.join(root,'validation/catalogs.mjs'))).digest('hex');
if(actual!==lock.files['catalogs.mjs'])throw Error(`Catalog rules differ from ${lock.local_override?'the local override of':'developer'} ${lock.commit}`);
const checks=await import('../validation/catalogs.mjs');
const config=JSON.parse(fs.readFileSync(path.join(root,'config/release-catalog.json'),'utf8'));
const products=checks.checkProducts(root,config.kind);
const pin=lock.local_override?`locally patched, upstream ${lock.local_override.upstream_commit.slice(0,8)}`:lock.commit.slice(0,8);
console.log(`Validated ${config.repository} products ${Object.keys(products).join(', ')} using developer catalog contract ${lock.contract_version} (${pin}).`);
